"""Record the table callers: eight voices announcing every tile and call.

Usage: python3 scripts/record-callers.py [workdir]
Writes src/audio/callers.gen.ts. Each caller has a short, bright, loud clip
for every phrase in scripts/caller-phrases.json (tile names and call words),
keyed by the phrase text. Uses the open Kokoro TTS model (Apache-2.0).
Needs: pip install kokoro-onnx soundfile; ffmpeg; kokoro-v1.0.onnx and voices-v1.0.bin in workdir.
"""
import base64, hashlib, json, os, re, subprocess, sys
import soundfile as sf
from kokoro_onnx import Kokoro

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pronounce import WORDS  # noqa: E402

work = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/tts'
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
phrases = json.load(open(os.path.join(root, 'scripts', 'caller-phrases.json')))

# id, display name, gender, Kokoro voice ("a+b@w" blends b in at share w).
CALLERS = [
    ('mei', 'Mei', 'female', 'af_heart+zf_xiaoxiao@0.5'),
    ('lin', 'Lin', 'female', 'af_bella+zf_xiaoyi@0.4'),
    ('grace', 'Grace', 'female', 'bf_emma'),
    ('sakura', 'Sakura', 'female', 'af_jessica+jf_alpha@0.35'),
    ('wei', 'Wei', 'male', 'am_michael+zm_yunxi@0.4'),
    ('george', 'George', 'male', 'bm_george'),
    ('kenji', 'Kenji', 'male', 'am_adam+jm_kumo@0.35'),
    ('omar', 'Omar', 'male', 'am_onyx'),
]

NUM = ['One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine']
SAY = {'Mah Jongg': 'Mahjong!'}
# Call words from other languages are spoken from IPA in their own language (pronounce.py).
# Claims and wins are shouted with excitement: quicker, higher and louder than a discard.
CALLS = {'Chow', 'Pung', 'Kong', 'Mahjong', 'Mah Jongg', 'Chi', 'Pon', 'Kan', 'Ron', 'Tsumo', 'Riichi', 'Pong', 'Gang', 'Hu', 'Zimo', 'Ăn', 'Phỗng', 'Chiếu', 'Ù'}
IPA = {w: WORDS[w] + '!' for w in ('Chi', 'Pon', 'Kan', 'Ron', 'Tsumo', 'Riichi', 'Hu', 'Zimo', 'Gang', 'Pong', 'Ăn', 'Phỗng', 'Chiếu', 'Ù')}

def speakable(p: str) -> str:
    if p in SAY:
        return SAY[p]
    m = re.match(r'^(\d) (.*)$', p)
    if m:
        p = f'{NUM[int(m.group(1)) - 1]} {m.group(2)}'
    return p + ('!' if p[-1] not in '!.?' else '')

def style_for(k, spec):
    if '+' not in spec:
        return spec
    a, rest = spec.split('+')
    b, w = rest.split('@')
    return k.get_voice_style(a) * (1 - float(w)) + k.get_voice_style(b) * float(w)

k = Kokoro(os.path.join(work, 'kokoro-v1.0.onnx'), os.path.join(work, 'voices-v1.0.bin'))
# Seed the caches from callers.gen.ts, so only changed phrases are synthesised.
gen = os.path.join(root, 'src', 'audio', 'callers.gen.ts')
have = {}
if os.environ.get('SEED') == '1' and os.path.exists(gen):
    txt = open(gen).read()
    have = {v['id']: v['clips'] for v in json.loads(txt[txt.index('= [') + 2:txt.rindex(';')])}

out = []
for cid, name, gender, spec in CALLERS:
    cache = os.path.join(work, 'callers', hashlib.sha1((spec + '|c1').encode()).hexdigest()[:10])
    os.makedirs(cache, exist_ok=True)
    style = style_for(k, spec)
    clips = {}
    for p in phrases:
        key = hashlib.sha1((p + ('|ipa1' if p in IPA else '') + ('|x1' if p in CALLS else '')).encode()).hexdigest()[:12]
        mp3 = os.path.join(cache, key + '.mp3')
        if not os.path.exists(mp3) and p not in CALLS and p in have.get(cid, {}):
            open(mp3, 'wb').write(base64.b64decode(have[cid][p].split(',', 1)[1]))
        if not os.path.exists(mp3):
            if p in IPA:
                audio, sr = k.create(IPA[p], voice=style, speed=1.15, is_phonemes=True)
            else:
                audio, sr = k.create(speakable(p), voice=style, speed=1.15 if p in CALLS else 1.08, lang='en-us')
            wav = os.path.join(cache, f'_t{os.getpid()}.wav')
            sf.write(wav, audio, sr)
            # Trim silence, lift the pitch a touch for energy, and make it loud.
            subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-af',
                            'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,' +
                            ('rubberband=pitch=1.12:formant=preserved,loudnorm=I=-11:TP=-0.5,apad=pad_dur=0.05' if p in CALLS else
                             'rubberband=pitch=1.04:formant=preserved,loudnorm=I=-13:TP=-1.0,apad=pad_dur=0.05'),
                            '-ac', '1', '-ar', '24000', '-b:a', '40k', mp3], check=True)
        clips[p] = 'data:audio/mpeg;base64,' + base64.b64encode(open(mp3, 'rb').read()).decode()
    out.append({'id': cid, 'name': name, 'gender': gender, 'clips': clips})
    print(name, 'done', flush=True)

with open(os.path.join(root, 'src', 'audio', 'callers.gen.ts'), 'w') as f:
    f.write('// Generated by scripts/record-callers.py. Do not edit.\n')
    f.write('/* eslint-disable */\n')
    f.write('export interface CallerVoice { id: string; name: string; gender: "female" | "male"; clips: Record<string, string> }\n')
    f.write('export const CALLER_VOICES: CallerVoice[] = ')
    json.dump(out, f)
    f.write(';\n')
print('wrote callers.gen.ts')
