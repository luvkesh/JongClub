// node scripts/blender/export-ts.mjs tile.json  ->  src/render/tileMesh.gen.ts
// Carries Blender's tile (scripts/blender/tile_model.py export) into the game as compact arrays.
import fs from 'fs';
const d = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const q = (a, k) => a.flat().map((v) => +v.toFixed(k));
let out = `// GENERATED by scripts/blender/export-ts.mjs from Blender's tile model (scripts/blender/tile_model.py).\n// Do not edit by hand: change the model and re-export. Positions in tile units, face toward +z.\n\nexport interface TileMeshPart { p: number[]; n: number[]; t: number[] }\nexport interface TileMeshLod { body: TileMeshPart; back: TileMeshPart; rim: TileMeshPart }\n\n`;
out += 'export const TILE_MESH: Record<\'lo\' | \'hi\', TileMeshLod> = {\n';
for (const lod of Object.keys(d)) {
  out += `  ${lod}: {\n`;
  for (const part of ['body', 'back', 'rim']) {
    const g = d[lod][part];
    out += `    ${part}: { p: [${q(g.p, 5)}], n: [${q(g.n, 4)}], t: [${g.t.flat()}] },\n`;
  }
  out += '  },\n';
}
out += '};\n';
fs.writeFileSync('src/render/tileMesh.gen.ts', out);
console.log('bytes', out.length);
