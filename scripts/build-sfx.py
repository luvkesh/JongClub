"""Prepare the recorded tile sound samples and embed them in src/audio/sfx.gen.ts.

Usage: python3 scripts/build-sfx.py <dir with the original dice-box-threejs public/sounds>
Writes assets/sfx/<name>.mp3 (trimmed, normalised, mono) and src/audio/sfx.gen.ts.
Needs ffmpeg and numpy.
"""
import base64, os, subprocess, sys, wave
import numpy as np

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'sfx')
os.makedirs(OUT, exist_ok=True)

# pool -> source files (dice-box-threejs public/sounds, MIT; upstream 3DDiceRoller, public domain)
POOLS = {
    'clack': [f'dicehit/dicehit_plastic{i}' for i in range(1, 16)],
    'wood': [f'dicehit/dicehit_wood{i}' for i in (1, 2, 3, 4, 6, 9, 12)],
    'metal': [f'dicehit/dicehit_metal{i}' for i in (1, 2, 4, 8, 10, 11)],
    'felt': [f'surfaces/surface_felt{i}' for i in (1, 2, 3, 4, 5, 7)],
    'table': [f'surfaces/surface_wood_table{i}' for i in range(1, 8)],
}
SR = 44100

def load(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.int16).astype(np.float64) / 32768

def prep(x):
    pk = np.abs(x).max()
    start = max(0, int(np.argmax(np.abs(x) > pk * 0.08)) - int(0.002 * SR))
    x = x[start:]
    env = np.abs(x)
    above = np.nonzero(env > pk * 10 ** (-54 / 20))[0]
    end = min(len(x), above[-1] + int(0.01 * SR)) if len(above) else len(x)
    x = x[:end].copy()
    fade = min(len(x), int(0.004 * SR))
    x[-fade:] *= np.linspace(1, 0, fade)
    x *= 10 ** (-1 / 20) / max(1e-9, np.abs(x).max())
    return x

def mp3(x, path):
    pcm = (np.clip(x, -1, 1) * 32767).astype(np.int16).tobytes()
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(SR), '-ac', '1', '-i', '-', '-codec:a', 'libmp3lame', '-b:a', '128k', path], input=pcm, check=True)

lines = ['// Generated by scripts/build-sfx.py: recorded tile and table samples as data URLs.', '// Sources and licences: README "Sound effects".', '', 'export const SFX: Record<string, string[]> = {']
total = 0
for pool, files in POOLS.items():
    urls = []
    for i, f in enumerate(files):
        x = prep(load(os.path.join(SRC, f + '.mp3')))
        name = f'{pool}-{i + 1}.mp3'
        p = os.path.join(OUT, name)
        mp3(x, p)
        b = open(p, 'rb').read()
        total += len(b)
        urls.append("'data:audio/mpeg;base64," + base64.b64encode(b).decode() + "'")
    lines.append(f'  {pool}: [\n    ' + ',\n    '.join(urls) + ',\n  ],')
lines.append('};\n')
open(os.path.join(ROOT, 'src', 'audio', 'sfx.gen.ts'), 'w').write('\n'.join(lines))
print(f'{sum(len(v) for v in POOLS.values())} samples, {total // 1024} KB')
